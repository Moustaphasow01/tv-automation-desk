export function normalizeOpportunityGateCodeV1(code, { classification = null } = {}) {
  const normalized = normalizeEnum(code);
  if (HARD_GATE_CODE_SET.has(normalized) || SOFT_GATE_CODE_SET.has(normalized)) return normalized;
  if (ALIASES[normalized]) return ALIASES[normalized];
  if (CONTEXTUAL_PREFIXES.some((prefix) => normalized.startsWith(prefix))) return "CONTEXTUAL_DATA_GAP";
  if (normalized.includes("OPTIONAL") && normalized.includes("MISSING")) return "OPTIONAL_INDICATOR_MISSING";
  return classification === "soft" ? "CONTEXTUAL_DATA_GAP" : "SCOPE_CONTRACT_MISMATCH";
}

function normalizeEnum(value) {
  return String(value || "").trim().toUpperCase().replaceAll("-", "_").replaceAll(" ", "_");
}
